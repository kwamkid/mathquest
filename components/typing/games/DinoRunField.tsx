// components/typing/games/DinoRunField.tsx
//
// "Dino Run" skin: a pixel dino runs in place at the left (legs swap between
// two frames); letter obstacles slide in from the right along the ground.
// Typing the obstacle's key(s) makes the dino jump it (destroy). One keystroke
// = one jump — punchy rhythm that suits the single-key stage-1 drill.
// Presentation only; state comes from GameFieldProps.
//
// Maps the engine's `progress` (0..1 threat-approach) to the obstacle's
// horizontal position: 105% (off-screen right) → 18% (at the dino).
//
// Sprites live in /public/game/dino-run: two run frames (leg swap) + a jump
// frame, all derived from the same base art so they align pixel-perfect.

'use client';

import { useEffect, useState } from 'react';
import { AnimatePresence, motion, useTransform } from 'framer-motion';
import RockText from '../RockText';
import type { GameFieldProps, LiveTarget } from './types';

// Leg-swap frames — regenerated by lifting ONLY the bottom foot rows (never
// the belly), so they're hole-free. run-1 lifts the right foot, run-2 the
// left; jump tucks both.
const DINO_RUN_1 = '/game/dino-run/dino-run-1.svg';
const DINO_RUN_2 = '/game/dino-run/dino-run-2.svg';
const DINO_JUMP = '/game/dino-run/dino-jump.svg';
// Boulder obstacle — colors are baked into the SVG (plain <img>, no mask
// tinting) because it needs two tones so the spin is visible.
const ROCK_IMG = '/game/dino-run/rock.svg';

// The dino stands here; obstacles travel from off-screen right down to it.
const DINO_X_PCT = 18;
const SPAWN_X_PCT = 105;
// Ground sits near the field bottom; the dino + obstacles rest on this line.
const GROUND_TOP_PCT = 78;

// Where an obstacle sits (in % of field width) at a given approach progress.
// The single source of truth for this skin's progress → x mapping: the
// boulders, the fireball's aim point and the destroy burst all use it, so a
// shot can never land somewhere the rock isn't.
const xAt = (progress: number) =>
  SPAWN_X_PCT - progress * (SPAWN_X_PCT - DINO_X_PCT);

export default function DinoRunField({
  targets,
  paused,
  shakeTick,
  laserTick,
  laserProgress,
  boom,
  onBoomDone,
  arrivalTick,
  spaceLabel,
}: GameFieldProps) {
  return (
    <>
      {/* Ground — Chrome-dino style: one thin line + small pebbles scattered
          along it, scrolling left so the dino reads as running. The line stays
          put; only the pebble layer moves. */}
      <div
        className="absolute inset-x-0 z-0 h-px bg-cyan-200/50"
        style={{ top: `${GROUND_TOP_PCT}%` }}
      />
      {/* Pebble layer — two side-by-side tiles of the same dash pattern slide
          left as one; when the first tile fully exits, the loop resets
          seamlessly (translateX 0 → -50% of a 200%-wide strip). */}
      <div
        className="pointer-events-none absolute inset-x-0 z-0 overflow-hidden"
        style={{ top: `calc(${GROUND_TOP_PCT}% + 3px)`, height: '8px' }}
      >
        <motion.div
          className="flex h-full w-[200%]"
          animate={paused ? { x: '0%' } : { x: ['0%', '-50%'] }}
          transition={
            paused
              ? { duration: 0 }
              : { duration: 6, repeat: Infinity, ease: 'linear' }
          }
        >
          <GroundPebbles />
          <GroundPebbles />
        </motion.div>
      </div>

      {/* The dino gunner. Recoils on each shot (laserTick), stumbles on a soft
          miss (arrivalTick). Outer div owns position + centering; inner divs
          own the recoil / stumble transforms so framer never clobbers the
          -translate-x-1/2 (the pill-overflow gotcha applies to any animated
          transform node). */}
      {/* GOTCHA (bitten twice now): the -translate-y-full lift MUST live on
          this plain, never-animated div. Putting it on a motion.div that has
          ANY `animate` (even {rotate:0}) lets framer overwrite the whole
          `transform`, the lift vanishes, and the dino hangs BELOW the ground
          line. Same rule as the -translate-x-1/2 pill-overflow bug. */}
      <div
        className="absolute z-10 -translate-x-1/2 -translate-y-full"
        style={{ left: `${DINO_X_PCT}%`, top: `${GROUND_TOP_PCT}%` }}
      >
        {/* Firing pose: each correct key (laserTick) rocks the dino back on
            its heels — a lean-back pivoting at the FEET (transformOrigin
            bottom) + a small kick, like absorbing the fireball's recoil. The
            sprite itself also swaps to the braced (tucked-legs) frame for the
            shot; see DinoSprite. */}
        <motion.div
          key={`recoil-${laserTick}`}
          style={{ transformOrigin: 'bottom center' }}
          animate={laserTick ? { x: [0, -7, 0], rotate: [0, -12, 0] } : { x: 0 }}
          transition={{ duration: 0.24, ease: 'easeOut' }}
        >
          {/* Stumble layer: bumped by arrivalTick → dip + tilt, then recover.
              Carries NO positioning classes (see gotcha above). */}
          <motion.div
            key={`stumble-${arrivalTick}`}
            animate={arrivalTick ? { rotate: [0, -18, 0], y: [0, 8, 0] } : { rotate: 0 }}
            transition={{ duration: 0.4, ease: 'easeInOut' }}
          >
            <DinoSprite shootTick={laserTick} paused={paused} />
          </motion.div>
        </motion.div>
      </div>

      {/* Fireball — flies from the dino's mouth to the obstacle on each
          correct key (laserTick). Aims at `laserProgress`, the active target's
          progress captured by the engine at the instant the key was pressed —
          NOT the live MotionValue, which on the killing keystroke has already
          been re-seated to the next rock. The bullet re-renders only when
          laserTick bumps; the boulder keeps sliding toward the shot, so they
          meet. */}
      <AnimatePresence>
        {laserTick > 0 && (
          <motion.div
            key={laserTick}
            className="pointer-events-none absolute z-10"
            style={{ top: `calc(${GROUND_TOP_PCT}% - 3rem)` }}
            initial={{ left: `${DINO_X_PCT + 3}%`, opacity: 1 }}
            animate={{
              // Stop at the boulder's NEAR (left) edge — its impact face —
              // not its center: the boulder is ~8% of the field wide, so
              // flying to the center reads as passing through it. Clamped so
              // a boulder right on top of the dino still gives a tiny flight.
              left: `${Math.max(xAt(laserProgress) - 5, DINO_X_PCT + 6)}%`,
              // Fully visible for the whole flight, then vanish AT impact —
              // no lingering shot for the boulder to roll past.
              opacity: [1, 1, 0],
            }}
            exit={{ opacity: 0 }}
            transition={{
              left: { duration: 0.22, ease: 'linear' },
              opacity: { duration: 0.24, times: [0, 0.92, 1] },
            }}
          >
            {/* Comet-style fire bullet: flickering flame tail + white-hot core
                with a layered orange/red glow. Centering lives on this plain
                div; the tail's flicker animation is on its own child node. */}
            <div className="flex -translate-x-1/2 items-center">
              <motion.div
                className="h-2 w-12 rounded-full bg-gradient-to-l from-amber-300 via-orange-500/70 to-transparent blur-[1.5px]"
                animate={{ scaleY: [1, 0.65, 1], opacity: [0.95, 0.7, 0.95] }}
                transition={{ duration: 0.12, repeat: Infinity }}
              />
              <div className="-ml-3 h-3.5 w-3.5 rounded-full bg-gradient-to-br from-white via-amber-200 to-orange-500 shadow-[0_0_10px_3px_rgba(251,146,60,0.85),0_0_22px_8px_rgba(239,68,68,0.45)]" />
            </div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Obstacles — boulders rolling in from the right; the kid types the
          letter(s) on the FRONT one to blast it. Keyed by slot, not by rock:
          slot 0's node always reads slot 0's MotionValue, so when the front
          boulder is destroyed the one behind it slides forward seamlessly
          (the engine re-seats the pool, keeping its progress). */}
      {targets.map((target, slot) => (
        <Boulder
          key={slot}
          target={target}
          paused={paused}
          shakeTick={shakeTick}
          laserTick={laserTick}
          spaceLabel={spaceLabel}
        />
      ))}

      {/* Obstacle-destroyed burst: the boulder is hit by the shot and
          shatters, exactly where it was (boom.progress is its approach value
          at destroy time). onAnimationComplete clears `boom` in the engine. */}
      <AnimatePresence>
        {boom && (
          <motion.div
            key={`dust-${boom.tick}`}
            className="pointer-events-none absolute z-20 -translate-x-1/2"
            style={{
              left: `${xAt(boom.progress)}%`,
              top: `calc(${GROUND_TOP_PCT}% - 1.5rem)`,
            }}
            initial={{ opacity: 1 }}
            animate={{ opacity: 0 }}
            transition={{ duration: 0.5 }}
            onAnimationComplete={onBoomDone}
          >
            {Array.from({ length: 6 }).map((_, i) => (
              <motion.span
                key={i}
                initial={{ x: 0, y: 0, scale: 1 }}
                animate={{
                  x: (i - 3) * 14 - 6,
                  y: -Math.abs((i - 3) * 6) - 4,
                  scale: 0,
                }}
                transition={{ duration: 0.5, ease: 'easeOut' }}
                className="absolute h-2 w-2 rounded-full bg-amber-200/80"
              />
            ))}
          </motion.div>
        )}
      </AnimatePresence>
    </>
  );
}

// One rolling boulder. The ROCK layer spins; the letter plate does NOT (it
// must stay readable). Outer div owns position + lift; shake and spin live on
// their own inner nodes.
// Only the ACTIVE boulder is typeable, so only it carries the current-char
// glow and reacts to hits — the one queued behind it just rolls in, dimmed,
// as a visible "here comes the next one".
function Boulder({
  target,
  paused,
  shakeTick,
  laserTick,
  spaceLabel,
}: {
  target: LiveTarget;
  paused: boolean;
  shakeTick: number;
  laserTick: number;
  spaceLabel: string;
}) {
  const { active } = target;
  // Obstacle x: slides from SPAWN_X_PCT → DINO_X_PCT as progress goes 0 → 1.
  const left = useTransform(target.progress, (v) => `${xAt(v)}%`);

  return (
    <motion.div
      style={{ left, top: `${GROUND_TOP_PCT}%` }}
      // Lift lives HERE (this node never gets a transform animation — framer
      // only drives style.left). On the shake layer below it would be
      // clobbered on the first wrong key and the boulder would drop to the
      // dino's level (the bug we shipped, twice).
      className={`absolute z-10 -translate-x-1/2 -translate-y-full ${
        active ? '' : 'opacity-60'
      }`}
    >
      <motion.div
        key={active ? shakeTick : 'queued'}
        animate={active && shakeTick ? { x: [0, -7, 7, -4, 0] } : undefined}
        transition={{ duration: 0.3 }}
      >
        {/* Impact flinch — a quick squash when the shot lands. Delayed to
            match the bullet's ~0.22s flight so the boulder reacts when the
            fireball ARRIVES, not when the key is pressed. Scale-only, on its
            own node (bugs.md rule). */}
        <motion.div
          key={`hit-${active ? laserTick : 'queued'}`}
          animate={active && laserTick ? { scale: [1, 0.9, 1] } : undefined}
          transition={{ delay: 0.18, duration: 0.16 }}
          className="relative"
        >
          {/* Spinning boulder — rolls leftward, so it rotates counter-
              clockwise. Spin is on its own node (rotation only, no
              positioning classes). Freezes while paused. */}
          <motion.div
            animate={paused ? undefined : { rotate: -360 }}
            transition={{ duration: 2.2, repeat: Infinity, ease: 'linear' }}
            className="h-14 w-14 sm:h-16 sm:w-16"
          >
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img
              src={ROCK_IMG}
              alt=""
              className="h-full w-full"
              draggable={false}
            />
          </motion.div>
          {/* Letter(s) locked on the boulder's center — NOT inside the
              spinner, so the glyphs never rotate. Centered via absolute +
              translate (not inset-0 flex) so a WIDE label like the Thai
              "เว้นวรรค (Space)" pill can overflow the small boulder instead
              of getting squeezed and wrapping to 3 lines. */}
          <div className="absolute left-1/2 top-1/2 -translate-x-1/2 -translate-y-1/2">
            <div className="rounded-lg bg-slate-900/85 px-2 py-1 shadow-lg ring-1 ring-white/10">
              <RockText
                text={target.rock.text}
                charIndex={target.charIndex}
                spaceLabel={spaceLabel}
                highlight={active}
              />
            </div>
          </div>
        </motion.div>
      </motion.div>
    </motion.div>
  );
}

// The dino sprite. Runs = the two leg frames swapped by a timer — a HARD cut
// (one masked layer whose src flips), so there's never a frame where both are
// faded and the black field shows through (the "black-dot flicker"). Jumping =
// the single tucked-legs frame. The source SVGs are solid black art, so we
// paint them via CSS mask — that lets us tint the dino bright over the dark
// field.
// The dino art viewBox is 246×261 (portrait) with its BOTTOM edge = the feet.
// The sprite box matches that aspect and bottom-anchors the mask, so the box's
// bottom edge IS the feet — no vertical slack to make the dino float.
const SPRITE_SIZE = 'h-16 w-[3.77rem] sm:h-20 sm:w-[4.71rem]';
// Leg-swap cadence (ms) — how long each run frame holds. Higher = calmer run.
const RUN_FRAME_MS = 160;

// Run = the two leg frames swapped by a timer (a HARD cut: one masked layer
// whose src flips instantly, so no black gap flickers between frames).
// Shooting = each shot (shootTick) holds the braced tucked-legs frame for the
// bullet's flight (~220ms), then the run cycle resumes. Paused = hold frame 1.
const SHOOT_POSE_MS = 220;

function DinoSprite({ shootTick, paused }: { shootTick: number; paused: boolean }) {
  const [frame, setFrame] = useState(0);
  const [shooting, setShooting] = useState(false);

  useEffect(() => {
    if (!shootTick) return;
    setShooting(true);
    const id = setTimeout(() => setShooting(false), SHOOT_POSE_MS);
    return () => clearTimeout(id);
  }, [shootTick]);

  useEffect(() => {
    if (shooting || paused) return;
    const id = setInterval(() => setFrame((f) => (f === 0 ? 1 : 0)), RUN_FRAME_MS);
    return () => clearInterval(id);
  }, [shooting, paused]);

  const src = shooting ? DINO_JUMP : frame === 0 ? DINO_RUN_1 : DINO_RUN_2;
  return <DinoLayer src={src} className={SPRITE_SIZE} />;
}

// One masked sprite layer, tinted via the mask fill (bright slate-100).
function DinoLayer({ src, className }: { src: string; className: string }) {
  return (
    <div
      className={`bg-slate-100 ${className}`}
      style={{
        WebkitMaskImage: `url(${src})`,
        maskImage: `url(${src})`,
        WebkitMaskRepeat: 'no-repeat',
        maskRepeat: 'no-repeat',
        WebkitMaskSize: 'contain',
        maskSize: 'contain',
        WebkitMaskPosition: 'bottom center',
        maskPosition: 'bottom center',
      }}
    />
  );
}

// One tile of scattered ground pebbles (small dashes at varied x / width), like
// the Chrome dino's ground specks. Two identical tiles sit side by side in the
// scroller so the pattern loops seamlessly. Positions are a fixed hand-picked
// spread (percent of tile width) — no randomness, so SSR and client match.
const PEBBLES: { left: number; w: number; up?: boolean }[] = [
  { left: 3, w: 10 },
  { left: 16, w: 4 },
  { left: 24, w: 14 },
  { left: 39, w: 5, up: true },
  { left: 47, w: 8 },
  { left: 58, w: 4 },
  { left: 66, w: 12 },
  { left: 79, w: 5 },
  { left: 85, w: 3, up: true },
  { left: 92, w: 9 },
];

function GroundPebbles() {
  return (
    <div className="relative h-full w-1/2 shrink-0">
      {PEBBLES.map((p, i) => (
        <span
          key={i}
          className="absolute h-px rounded-full bg-cyan-200/35"
          style={{
            left: `${p.left}%`,
            width: `${p.w}px`,
            top: p.up ? '0px' : '4px',
          }}
        />
      ))}
    </div>
  );
}
